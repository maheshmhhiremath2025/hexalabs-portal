#!/usr/bin/env node
/**
 * Generate nginx site configs for every whitelabel domain in Mongo.
 *
 * For each Organization with a `customDomain` field, write a complete
 * nginx site to /etc/nginx/sites-available/<domain> and symlink into
 * sites-enabled. The output is guaranteed to include the standard pieces:
 *
 *   - HTTP→HTTPS redirect (with ACME challenge passthrough for certbot renewals)
 *   - SSL block (only if the cert already exists; otherwise an HTTP-only stub
 *     is emitted so certbot can do its first issuance against the running server)
 *   - Per-tenant `root /var/www/whitelabel/<slug>/` for the pre-baked index.html
 *   - Shared `/assets/`, `/logo/`, image-extension paths pointing at the
 *     canonical frontend `dist`
 *   - `/api/` proxy to the backend on 127.0.0.1:8001 (same-origin API for
 *     SPA → no CORS, no need for client networks to reach api.hexalabs.online)
 *   - SPA fallback (`try_files`) and aggressive no-cache on the index
 *
 * Usage:
 *   node scripts/generate-whitelabel-nginx.js              # all domains
 *   node scripts/generate-whitelabel-nginx.js labs.foo.com # one domain
 *   node scripts/generate-whitelabel-nginx.js --dry-run    # print, don't write
 *
 * After running:
 *   nginx -t && systemctl reload nginx
 *
 * If a cert isn't found, you'll see a warning like:
 *   WARN labs.foo.com — no SSL cert at /etc/letsencrypt/live/...
 *        emitted HTTP-only stub. Run:
 *        certbot --nginx -d labs.foo.com
 *        then re-run this script to add the SSL block.
 */

require('dotenv').config({ path: '/root/synergific-portal/dockerfiles/backend/.env' });
const mongoose = require('mongoose');
const fs = require('fs');
const path = require('path');

const SITES_AVAILABLE = '/etc/nginx/sites-available';
const SITES_ENABLED = '/etc/nginx/sites-enabled';
const WL_INDEX_ROOT = '/var/www/whitelabel';
const SHARED_DIST   = '/opt/getlabs/portal.synergificsoftware.com/frontend/dist';
const BACKEND_UPSTREAM = 'http://127.0.0.1:8001';
const CERT_BASE = '/etc/letsencrypt/live';

const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const filterDomain = args.find(a => !a.startsWith('--'));

function slugFor(orgName) {
  return String(orgName || '').toLowerCase().replace(/[^a-z0-9]+/g, '');
}

function emit(domain, slug) {
  const certPath = path.join(CERT_BASE, domain, 'fullchain.pem');
  const haveSSL = fs.existsSync(certPath);

  const banner =
`# ──────────────────────────────────────────────────────────────────────
# ${domain} whitelabel — generated by scripts/generate-whitelabel-nginx.js.
# DO NOT hand-edit. Re-run the generator after Mongo branding changes:
#   node scripts/generate-whitelabel-nginx.js ${domain}
# Re-bake the per-tenant index.html after every frontend build:
#   node scripts/generate-whitelabel-index.js
# ──────────────────────────────────────────────────────────────────────
`;

  const httpServer =
`server {
    listen 80;
    server_name ${domain};
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location / { return 301 https://$host$request_uri; }
}
`;

  const apiLocation =
`    # Same-origin API proxy. The whitelabel SPA's apiCaller detects it is
    # NOT on a canonical host and uses baseURL='/api', so calls land here
    # and never hit api.hexalabs.online directly. Keeps the SPA functional
    # on client networks that block the canonical API host.
    location /api/ {
        proxy_pass ${BACKEND_UPSTREAM}/;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Forwarded-Host $host;
        proxy_read_timeout 600s;
        proxy_send_timeout 600s;
        proxy_connect_timeout 60s;
        client_max_body_size 100M;
    }`;

  const sharedAssets =
`    # Hashed assets + logos + favicons — shared with the canonical dist
    location /assets/ { root ${SHARED_DIST}; }
    location /logo/   { root ${SHARED_DIST}; }
    location ~ \\.(svg|png|ico|webp|woff2?|ttf|jpg|jpeg|gif)$ {
        root ${SHARED_DIST};
        try_files $uri =404;
    }`;

  const spaFallback =
`    location / {
        try_files $uri $uri/ /index.html;
        add_header Cache-Control "no-cache, no-store, must-revalidate";
        add_header Pragma "no-cache";
        add_header Expires 0;
    }`;

  let httpsServer;
  if (haveSSL) {
    httpsServer =
`server {
    listen 443 ssl;
    server_name ${domain};

    ssl_certificate     ${certPath};
    ssl_certificate_key /etc/letsencrypt/live/${domain}/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;

    client_max_body_size 100M;

    # Per-tenant index.html (window.__BRANDING__ pre-injected) lives here
    root ${WL_INDEX_ROOT}/${slug};
    index index.html;

${apiLocation}

${sharedAssets}

${spaFallback}
}
`;
  } else {
    httpsServer =
`# WARN: SSL cert not yet issued for ${domain}.
# Run once to issue:  certbot --nginx -d ${domain}
# Then re-run:        node scripts/generate-whitelabel-nginx.js ${domain}
server {
    listen 80;
    server_name ${domain};

    client_max_body_size 100M;
    root ${WL_INDEX_ROOT}/${slug};
    index index.html;

${apiLocation}

${sharedAssets}

${spaFallback}
}
`;
  }

  return { content: banner + (haveSSL ? httpServer + '\n' : '') + httpsServer, haveSSL };
}

(async () => {
  await mongoose.connect(process.env.MONGO_URI, { serverSelectionTimeoutMS: 15000 });
  const Organization = require('/root/synergific-portal/dockerfiles/backend/models/organization');

  const filter = { customDomain: { $exists: true, $ne: '' } };
  const orgs = await Organization.find(filter).lean();
  if (orgs.length === 0) {
    console.log('no organizations with customDomain set; nothing to do');
    process.exit(0);
  }

  let written = 0, skipped = 0, warnings = 0;
  for (const org of orgs) {
    const domain = String(org.customDomain).trim().toLowerCase();
    if (filterDomain && filterDomain !== domain) { skipped++; continue; }
    const slug = slugFor(org.organization);
    const { content, haveSSL } = emit(domain, slug);
    const outFile = path.join(SITES_AVAILABLE, domain);
    const symlink = path.join(SITES_ENABLED, domain);

    if (dryRun) {
      console.log(`---- ${outFile} ----\n${content}`);
      continue;
    }
    if (fs.existsSync(outFile)) {
      const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
      fs.copyFileSync(outFile, outFile + '.bak-' + stamp);
    }
    fs.writeFileSync(outFile, content);
    if (!fs.existsSync(symlink)) {
      try { fs.symlinkSync(path.relative(SITES_ENABLED, outFile), symlink); }
      catch (e) { console.log(`symlink failed for ${domain}: ${e.message}`); }
    }
    const sslState = haveSSL ? 'with SSL' : 'HTTP-only stub (cert not found, certbot needed)';
    console.log(`wrote ${outFile} (${domain} → ${org.organization}) ${sslState}`);
    if (!haveSSL) warnings++;
    written++;
  }

  console.log(`\nwrote=${written} skipped=${skipped} warnings=${warnings}`);
  console.log('next: run `nginx -t && systemctl reload nginx` to apply');
  await mongoose.disconnect();
})().catch(e => { console.error('FATAL', e); process.exit(1); });
